#!/usr/bin/env python3
"""Refresh the upstream mirrors and their bundles, and regenerate their manifest.

A single upstream repository disappearing should not be able to stop this project. Each upstream we
depend on is cloned as a bare mirror, bundled, and kept on the NAS beside our own mirror.

`MANIFEST.md` beside the bundles is written here rather than by hand, for the same reason the mirror's
own README is generated: a hand-written manifest naming a refresh command that does not exist is worse
than no manifest at all, which is exactly what happened to the first version of this file.

Run monthly from the same job that watches the successor repositories. Silent on success unless
something changed or failed, because a monthly notification that says nothing happened is noise.
"""
from __future__ import annotations

import datetime
import pathlib
import subprocess
import sys

MIRRORS = pathlib.Path.home() / "upstream-mirrors"
BUNDLES = MIRRORS / "out"


def _nas_upstream_dir() -> pathlib.Path | None:
    """Find the NAS mirror directory by looking, never by assuming a path.

    A hardcoded answer here has already gone wrong once: the GVFS mount name ends in `,user=<name>`,
    and a path built from a truncated copy of it silently pointed at nothing.
    """
    root = pathlib.Path("/run/user/1000/gvfs")
    for mount in sorted(root.glob("smb-share:server=*")):
        candidate = mount / "AI Projects" / "hermes-voice-satellite" / "upstream"
        if candidate.parent.is_dir():
            return candidate
    return None


REPOS = {
    "wyoming-satellite": "https://github.com/rhasspy/wyoming-satellite",
    # rhasspy, not OHF-Voice, even though the sibling projects moved: the OHF-Voice path for this one
    # returns "Repository not found" (checked 2026-09-24, the first time this script had to clone it
    # from scratch rather than update an existing mirror).
    "wyoming-openwakeword": "https://github.com/rhasspy/wyoming-openwakeword",
    "wyoming": "https://github.com/OHF-Voice/wyoming",
    "seeed-voicecard": "https://github.com/respeaker/seeed-voicecard",
    "linux-voice-assistant": "https://github.com/OHF-Voice/linux-voice-assistant",
    "silero-vad": "https://github.com/snakers4/silero-vad",
}

# Why each upstream matters to this project. Hand-maintained: this is judgement, not something git
# can report.
WHY = {
    "wyoming-satellite": "the satellite software itself, and the project we are taking over. "
                         "Deprecated upstream, so the most at risk",
    "wyoming-openwakeword": "the wake engine. Previously existed only on the device's SD card",
    "wyoming": "the protocol library the transport is built on",
    "seeed-voicecard": "the audio driver, so a kernel change can be answered with a diff",
    "linux-voice-assistant": "the successor project, watched for feature ideas",
    "silero-vad": "the voice detector. It decides whether the device hears a person, so it is the "
                  "one dependency whose disappearance would stop the product working",
}

# Facts about our own use of an upstream, which git cannot report. Hand-maintained.
NOTES = {
    "wyoming-satellite": "our vendored snapshot is `13bb024` from 2025-04-25, so check the mirrored "
                         "commits here before assuming our copy is current",
    "silero-vad": "the ONNX model we actually run is vendored in `bridge/vendor/` and tracked in our "
                  "own repository with its checksum (`docs/voice-detection.md`), because a detector "
                  "that decides whether the device hears its owner must not depend on an asset "
                  "living inside someone else's wheel. This mirror is the source of record for "
                  "regenerating and checking that file, not a runtime dependency",
}


def sh(*args, cwd=None):
    p = subprocess.run(args, cwd=cwd, capture_output=True, text=True, timeout=300)
    return p.returncode, ((p.stdout or "") + (p.stderr or "")).strip()


def head_of(mirror: pathlib.Path) -> tuple[str, str]:
    """The mirror's head commit, short, and its date. Never guesses: reports `unknown` instead."""
    rc, out = sh("git", "-C", str(mirror), "log", "-1", "--format=%h %ad", "--date=short")
    if rc or not out:
        return "unknown", "unknown"
    parts = out.split()
    return parts[0], parts[1] if len(parts) > 1 else "unknown"


def manifest_text(rows: list[tuple[str, str, str, str]], mirrored_on: str) -> str:
    lines = [
        "# Upstream mirrors",
        "",
        "Bare mirrors of every upstream this project depends on, kept because a single repository",
        "disappearing should not stop development. Each is stored as a `git bundle`, which is a complete,",
        "restorable copy including all history: `git clone <name>.bundle <dir>`.",
        "",
        f"Mirrored {mirrored_on}. **Generated by `scripts/refresh-upstream-mirrors.py` in the",
        "repository**, which the monthly `watch-successor-voice-repos` job runs. Do not edit this file by",
        "hand: the next refresh overwrites it, and no hand edit here is protected by anything.",
        "",
        "| Upstream | Why we depend on it | Mirrored at | Date |",
        "|---|---|---|---|",
    ]
    for name, url, head, date in rows:
        slug = url.removeprefix("https://github.com/")
        lines.append(f"| `{slug}` | {WHY.get(name, '')} | `{head}` | {date} |")
    for name, note in NOTES.items():
        lines.append("")
        lines.append(f"Note on `{name}`: {note}.")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    MIRRORS.mkdir(exist_ok=True)
    BUNDLES.mkdir(exist_ok=True)
    changed, problems, rows = [], [], []
    for name, url in REPOS.items():
        d = MIRRORS / name
        if not d.exists():
            rc, out = sh("git", "clone", "--mirror", "--quiet", url, str(d))
            if rc:
                problems.append(f"{name}: clone failed: {out[:120]}")
                continue
            changed.append(f"{name}: first mirror")
        else:
            before = sh("git", "-C", str(d), "rev-parse", "HEAD")[1]
            rc, out = sh("git", "-C", str(d), "remote", "update", "--prune")
            if rc:
                problems.append(f"{name}: fetch failed: {out[:120]}")
                continue
            after = sh("git", "-C", str(d), "rev-parse", "HEAD")[1]
            if before != after:
                changed.append(f"{name}: {before[:8]} -> {after[:8]}")
        sh("git", "-C", str(d), "bundle", "create", str(BUNDLES / f"{name}.bundle"), "--all")
        rows.append((name, url, *head_of(d)))
        nas = _nas_upstream_dir()
        if nas is not None:
            nas.mkdir(parents=True, exist_ok=True)
            sh("cp", str(BUNDLES / f"{name}.bundle"), str(nas / f"{name}.bundle"))
        else:
            problems.append(f"{name}: NAS mirror directory not found, bundle kept locally only")

    manifest = manifest_text(rows, datetime.date.today().isoformat())
    try:
        (MIRRORS / "MANIFEST.md").write_text(manifest)
        nas = _nas_upstream_dir()
        if nas is not None:
            (nas / "MANIFEST.md").write_text(manifest)
    except OSError as exc:
        problems.append(f"manifest not written: {type(exc).__name__}")

    if changed:
        print("upstream mirrors updated: " + "; ".join(changed))
    if problems:
        print("upstream mirror problems: " + "; ".join(problems), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
