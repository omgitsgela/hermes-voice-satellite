#!/usr/bin/env python3
"""Run ON the satellite, as root: set VS_MIC_MUTE_AFTER_AWAKE, the wake-tone mute margin.

The satellite mutes the microphone for (awake wav duration + THIS value) after the wake tone.
The value lives in the machine's config file, NOT in the unit: since issue #45 the unit expands
`--mic-seconds-to-mute-after-awake-wav "$VS_MIC_MUTE_AFTER_AWAKE"` from
/etc/voice-satellite/satellite.env, so that file is the one source of truth. Writing a literal into
the unit instead (which is what this script used to do) silently stops the env file from mattering.

* Too large, and it eats the onset of the user's speech before it is ever recorded. Observed
  2026-09-22: a 0.6 s margin (+ a 308 ms tone = 908 ms total) swallowed the front of the first
  word. The same bug came back on 2026-09-29 at 0.4 (708 ms total): speaking promptly, "New
  conversation" was transcribed as "conversation", so the phrase matcher never fired, while the
  same words after a pause came through whole at 0.7 s. The tell is a recording that opens at full
  level with no lead-in, and a captured speech duration that is one word short.
* Too small, and the tone's acoustic tail leaks into the recording.

The chosen awake tone is 308 ms with an exponential decay, so 0.1 s covers the acoustic tail
without clipping speech: about 408 ms total. That is the value to keep.

    scp scripts/set_satellite_mute.py <satellite>:/tmp/
    ssh <satellite> 'sudo python3 /tmp/set_satellite_mute.py 0.1'
    ssh <satellite> 'sudo systemctl restart wyoming-satellite.service'

The env file is read at service start, so unlike the tone WAVs (re-read per detection) this needs a
restart to take effect. The host-side bound is asserted by scripts/test_wake_mute_timing.py.
"""

import re
import sys
from pathlib import Path

ENV = Path("/etc/voice-satellite/satellite.env")
UNIT = Path("/etc/systemd/system/wyoming-satellite.service")
NAME = "VS_MIC_MUTE_AFTER_AWAKE"
FLAG = "--mic-seconds-to-mute-after-awake-wav"
TONE_SECONDS = 0.308       # sounds/awake.wav, generated by scripts/make_chimes.py
MAX_TOTAL_SECONDS = 0.45   # measured-good bound: 408 ms was a natural onset, 708 ms clipped it

if len(sys.argv) != 2:
    sys.exit(f"usage: {sys.argv[0]} <seconds>")
try:
    value = float(sys.argv[1])
except ValueError:
    sys.exit(f"not a number: {sys.argv[1]!r}")
if not 0 <= value <= 2:
    sys.exit("refusing: value must be between 0 and 2 seconds")

if not ENV.exists():
    sys.exit(f"REFUSING: {ENV} is not there; is the satellite installed?")
text = ENV.read_text()
if not re.search(rf"^{NAME}=", text, re.MULTILINE):
    sys.exit(f"REFUSING: {NAME} is not in {ENV}; run the installer first")

unit = UNIT.read_text() if UNIT.exists() else ""
if f'{FLAG} "${NAME}"' not in unit:
    print(f"WARNING: {UNIT} does not expand ${NAME}, so {ENV} may not be what the satellite"
          " actually reads; check the unit\n")

updated = re.sub(rf"^{NAME}=.*$", f"{NAME}={value}", text, flags=re.MULTILINE)
if updated == text:
    print(f"already set to {value}")
else:
    ENV.write_text(updated)
    print(f"set {NAME}={value} in {ENV}")

total = TONE_SECONDS + value
print(f"\ntotal deaf microphone after the wake tone: {total * 1000:.0f} ms"
      f" (tone {TONE_SECONDS * 1000:.0f} ms + margin {value * 1000:.0f} ms)")
if total > MAX_TOTAL_SECONDS:
    print(f"WARNING: past the measured-good bound of {MAX_TOTAL_SECONDS * 1000:.0f} ms. Both 908 ms"
          " and 708 ms clipped the onset of the user's first word.")
    print("         The bridge's own WAKE_QUIET_SECONDS must stay under this total as well.")
print("\nrestart to apply:  sudo systemctl restart wyoming-satellite.service")
